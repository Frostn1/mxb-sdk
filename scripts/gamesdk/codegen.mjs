import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const schemaPath = path.join(root, "schema/game-sdk.schema.json");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const defs = schema.$defs;
const header = "// GENERATED by scripts/gamesdk/codegen.mjs from schema/game-sdk.schema.json. Do not edit.\n";

const refName = (ref) => ref.slice(ref.lastIndexOf("/") + 1);
const doc = (text, indent = "") => `${indent}/** ${String(text).replaceAll("*/", "*\\/")} */\n`;

function tsType(s) {
  if (s.$ref) return refName(s.$ref);
  if (Object.hasOwn(s, "const")) return JSON.stringify(s.const);
  if (s.oneOf) return s.oneOf.map(tsType).join(" | ");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(s.type)) return s.type.map((t) => tsType({ type: t })).join(" | ");
  if (s.type === "array") {
    if (s.prefixItems) return `[${s.prefixItems.map(tsType).join(", ")}]`;
    return `${tsType(s.items ?? {})}[]`;
  }
  if (s.type === "object") {
    if (!s.properties) return "Record<string, unknown>";
    const required = new Set(s.required ?? []);
    return `{ ${Object.entries(s.properties).map(([k, v]) => `${JSON.stringify(k)}${required.has(k) ? "" : "?"}: ${tsType(v)}`).join("; ")} }`;
  }
  return { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null" }[s.type] ?? "unknown";
}

function emitTsDef(name, s) {
  if (s.type === "object" && s.properties) {
    const required = new Set(s.required ?? []);
    let out = doc(s.description) + `export interface ${name} {\n`;
    for (const [key, value] of Object.entries(s.properties)) {
      out += doc(value.description ?? key, "  ");
      out += `  ${key}${required.has(key) ? "" : "?"}: ${tsType(value)};\n`;
    }
    return out + "}\n";
  }
  return doc(s.description) + `export type ${name} = ${tsType(s)};\n`;
}

let ts = header;
ts += `export const SCHEMA_VERSION = ${JSON.stringify(schema["x-schema-version"])} as const;\n`;
ts += `export const SDK_VERSION = ${JSON.stringify(schema["x-sdk-version"])} as const;\n\n`;
ts += `/** Event discriminators recognized by this SDK version. */\n`;
ts += `export const GAME_EVENT_TYPES = ${JSON.stringify(eventBranches().map((branch) => branch.properties.type.const))} as const;\n\n`;
for (const [name, def] of Object.entries(defs)) ts += emitTsDef(name, def) + "\n";

const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replaceAll("-", "_").toLowerCase();
const pascal = (s) => s.replace(/(^|[_-])([a-z0-9])/g, (_, _p, c) => c.toUpperCase());
const rustEnums = new Map();

function enumName(owner, field, s) {
  const name = field ? `${owner}${pascal(field)}` : owner;
  rustEnums.set(name, s.enum.filter((v) => v !== null));
  return name;
}

function rustType(s, owner = "Value", field = "") {
  if (s.$ref) return refName(s.$ref);
  if (Object.hasOwn(s, "const")) {
    if (typeof s.const === "boolean") return "bool";
    return "String";
  }
  if (s.oneOf) {
    const nonNull = s.oneOf.filter((x) => x.type !== "null");
    if (nonNull.length === 1 && nonNull.length !== s.oneOf.length) return `Option<${rustType(nonNull[0], owner, field)}>`;
    return "serde_json::Value";
  }
  if (s.enum) {
    const nullable = s.enum.includes(null);
    const ty = enumName(owner, field, s);
    return nullable ? `Option<${ty}>` : ty;
  }
  if (Array.isArray(s.type)) {
    const nonNull = s.type.filter((t) => t !== "null");
    if (nonNull.length === 1 && nonNull.length !== s.type.length) return `Option<${rustType({ ...s, type: nonNull[0], enum: undefined }, owner, field)}>`;
  }
  if (s.type === "array") {
    if (s.prefixItems) return `[${rustType(s.prefixItems[0], owner, field)}; ${s.prefixItems.length}]`;
    return `Vec<${rustType(s.items ?? {}, owner, field)}>`;
  }
  if (s.type === "object") return "serde_json::Value";
  return { string: "String", integer: "i64", number: "f64", boolean: "bool", null: "()" }[s.type] ?? "serde_json::Value";
}

function rustFieldName(name) {
  const out = snake(name);
  // Every Rust keyword a schema field could be named: serde reads the raw identifier `r#use`
  // as `use`, so the JSON name is unchanged.
  const keywords = ["as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
    "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe",
    "use", "where", "while", "abstract", "become", "box", "do", "final", "gen", "macro", "override",
    "priv", "try", "typeof", "unsized", "virtual", "yield"];
  return keywords.includes(out) ? `r#${out}` : out;
}

function emitRustStruct(name, s, skip = new Set()) {
  const required = new Set(s.required ?? []);
  let out = `/// ${s.description ?? name}\n#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(rename_all = "camelCase")]\npub struct ${name} {\n`;
  for (const [key, value] of Object.entries(s.properties ?? {})) {
    if (skip.has(key)) continue;
    let ty = rustType(value, name, key);
    if (!required.has(key) && !ty.startsWith("Option<")) ty = `Option<${ty}>`;
    out += `    /// ${value.description ?? key}\n`;
    if (!required.has(key)) out += "    #[serde(skip_serializing_if = \"Option::is_none\")]\n";
    out += `    pub ${rustFieldName(key)}: ${ty},\n`;
  }
  return out + "}\n";
}

function eventBranches() {
  return defs.GameEvent.oneOf.map((x) => defs[refName(x.$ref)]);
}

let rust = header + "\n";
rust += `/// Serialized schema major supported by these generated types.\n`;
rust += `pub const SCHEMA_VERSION: u32 = ${schema["x-schema-version"]};\n`;
rust += `/// Semantic version of the Game SDK represented by these generated types.\n`;
rust += `pub const SDK_VERSION: &str = ${JSON.stringify(schema["x-sdk-version"])};\n\n`;

// Discover property enums before emitting them.
for (const [name, def] of Object.entries(defs)) {
  if (def.enum) enumName(name, "", def);
  for (const [field, value] of Object.entries(def.properties ?? {})) if (value.enum) enumName(name, field, value);
}
for (const [name, values] of rustEnums) {
  rust += `/// ${defs[name]?.description ?? `Allowed ${name} values.`}\n`;
  rust += `#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(rename_all = "snake_case")]\npub enum ${name} {\n`;
  for (const value of values) {
    const variant = pascal(String(value).replace(/^[^a-zA-Z]+/, "value_"));
    if (snake(variant) !== value) rust += `    #[serde(rename = ${JSON.stringify(value)})]\n`;
    rust += `    /// Serialized as ${JSON.stringify(value)}.\n`;
    rust += `    ${variant},\n`;
  }
  rust += "}\n\n";
}

for (const [name, def] of Object.entries(defs)) {
  if (def.enum || name === "GameEvent" || name.endsWith("Event") || ["EventStart","EventEnd","OnTrack","OffTrack","SessionStart","SessionState","SessionEnd"].includes(name)) continue;
  if (def.type === "object") rust += emitRustStruct(name, def) + "\n";
}

rust += `/// Common fields on every game event.\n#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(rename_all = "camelCase")]\npub struct Event {\n    /// Event sequence number.\n    pub seq: i64,\n    /// Event time in Unix ms.\n    pub at: i64,\n    /// Related race number, when the emitter has one.\n    #[serde(skip_serializing_if = "Option::is_none")]\n    pub race_num: Option<i64>,\n    /// Whether this concerns the player, when known.\n    #[serde(skip_serializing_if = "Option::is_none")]\n    pub local: Option<bool>,\n    /// Event-specific fields and type tag.\n    #[serde(flatten)]\n    pub kind: EventKind,\n}\n\n/// Backward-compatible name for a typed game event.\npub type GameEvent = Event;\n\n`;
rust += `/// Per-type game event fields.\n#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(tag = "type", rename_all = "snake_case", rename_all_fields = "camelCase")]\npub enum EventKind {\n`;
for (const branch of eventBranches()) {
  const type = branch.properties.type.const;
  const variant = pascal(type);
  const fields = Object.entries(branch.properties).filter(([k]) => !["seq", "at", "type", "raceNum", "local"].includes(k));
  rust += `    /// ${branch.description}\n    ${variant}`;
  if (!fields.length) rust += ",\n";
  else {
    rust += " {\n";
    const required = new Set(branch.required ?? []);
    for (const [key, value] of fields) {
      let ty = rustType(value, `${variant}Event`, key);
      if (!required.has(key) && !ty.startsWith("Option<")) ty = `Option<${ty}>`;
      rust += `        /// ${value.description}\n`;
      if (!required.has(key)) rust += "        #[serde(skip_serializing_if = \"Option::is_none\")]\n";
      rust += `        ${rustFieldName(key)}: ${ty},\n`;
    }
    rust += "    },\n";
  }
}
rust += "}\n";

const outputs = [
  [path.join(root, "packages/mxb-game/src/types.gen.ts"), ts],
  [path.join(root, "crates/mxb-game/src/types.rs"), rust],
];
let different = false;
for (const [file, content] of outputs) {
  const old = await readFile(file, "utf8").catch(() => "");
  if (old.replaceAll("\r\n", "\n") === content) continue;
  different = true;
  if (process.argv.includes("--check")) console.error(`${path.relative(root, file)} is out of date`);
  else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}
if (process.argv.includes("--check") && different) process.exitCode = 1;
